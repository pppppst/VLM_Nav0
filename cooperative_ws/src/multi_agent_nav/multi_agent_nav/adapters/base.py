from typing import Protocol
from ..models import Health, Pose2D

class RobotAdapter(Protocol):
    """Planning/scanning return Futures; motion results enter the results queue."""
    def get_health(self) -> Health: ...
    def compute_path(self, local_goal: Pose2D): ...
    def select_approach(self, local_object: Pose2D, excluded_candidates): ...
    def start_navigation(self, local_goal, task_id, command_id, goal_kind) -> str: ...
    def cancel_navigation(self, goal_id): ...
    def start_scan(self, target_descriptions, scan_id): ...
    def stop_motion(self, reason): ...

