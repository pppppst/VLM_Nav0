from typing import Protocol
from ..models import Health, Pose2D

class ScanSpinAborted(RuntimeError):
    """A terminal Spin abort; resuming still requires a confirmed stop and obstacle."""

class RobotAdapter(Protocol):
    """Planning/scanning return Futures; motion results enter the results queue."""
    def get_health(self) -> Health: ...
    def compute_path(self, local_goal: Pose2D): ...
    def select_approach(self, local_object: Pose2D, excluded_candidates, *, standoff_distance=None, path_accept=None): ...
    def read_approach_parameters(self): ...
    def costmap_transform(self, global_goal=False): ...
    def costmap_candidate_free(self, candidate, global_goal=False): ...
    def observation_candidate_free(self, candidate): ...
    def local_rotation_check(self, candidate): ...
    def approach_candidate_free(self, candidate): ...
    def start_navigation(self, local_goal, task_id, command_id, goal_kind) -> str | None: ...
    def cancel_navigation(self, goal_id): ...
    def start_scan(self, target_descriptions, scan_id, *, stop_on_target=None, current_view_only=False, task_id=''): ...
    def stop_motion(self, reason): ...

